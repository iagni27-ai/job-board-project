export function CategoryIcon({ slug, className = "w-5 h-5", ...props }) {
  switch (slug) {
    case "teknologi":
      return <CodeIcon className={className} {...props} />;
    case "desain":
      return <PaletteIcon className={className} {...props} />;
    case "pemasaran":
      return <MegaphoneIcon className={className} {...props} />;
    case "keuangan":
      return <ChartIcon className={className} {...props} />;
    case "pendidikan":
      return <GraduationCapIcon className={className} {...props} />;
    case "kesehatan":
      return <StethoscopeIcon className={className} {...props} />;
    default:
      return <BriefcaseIcon className={className} {...props} />;
  }
}
